import { LightningElement, api } from "lwc";
import { isLockedState } from "prolet/wizardUtils";
import PHOTO from "@salesforce/resourceUrl/CarRentalPhoto";
import STEP_PHOTO_1 from "@salesforce/resourceUrl/CarRentalPhotoCar";
import STEP_PHOTO_2 from "@salesforce/resourceUrl/CarRentalPhotoExtras";

// WIZARD-MAKER:frame {"steps":"stepper","buttons":"spread","width":"medium","heading":true,"look":{"background":"gradient","colors":["#ece6ff","#dbe8ff"],"card":true,"photo":"side","photoSize":"medium","photoText":null,"steps":{"CarRentalCar":{"photo":"banner"},"CarRentalInvoice":{"photo":"none"},"CarRentalSummary":{"photo":"none"}}}}
/**
 * The frame of the carRental wizard: its steps and buttons, around the content of every page.
 *   <c-car-rental-frame page={page} model={model} data={data} l={l} state={state} errors={errors}> …the page… </c-car-rental-frame>
 *
 * WIZARD-MAKER: generated by "npm run make layout". It is written again when the frame is changed
 * and when pages are added, moved or get a condition, so changes made by hand here are replaced.
 */

/** The wizard's look (change it with "npm run make style"). */
const WIZARD_LOOK = {
  background: "gradient",
  colors: ["#ece6ff", "#dbe8ff"],
  card: true,
  photo: "side",
  photoSize: "medium"
};

/** The look of every step: the wizard's, with what a step changes for itself. */
const LOOKS = {
  CarRentalDriver: {
    background: "gradient",
    colors: ["#ece6ff", "#dbe8ff"],
    card: true,
    photo: "side",
    photoSize: "medium"
  },
  CarRentalCar: {
    background: "gradient",
    colors: ["#ece6ff", "#dbe8ff"],
    card: true,
    photo: "banner",
    photoSize: "medium"
  },
  CarRentalExtras: {
    background: "gradient",
    colors: ["#ece6ff", "#dbe8ff"],
    card: true,
    photo: "side",
    photoSize: "medium"
  },
  CarRentalInvoice: {
    background: "gradient",
    colors: ["#ece6ff", "#dbe8ff"],
    card: true,
    photo: "none",
    photoSize: "medium"
  },
  CarRentalSummary: {
    background: "gradient",
    colors: ["#ece6ff", "#dbe8ff"],
    card: true,
    photo: "none",
    photoSize: "medium"
  }
};

/** The background photo of every step that has one. */
const BACKGROUND_PHOTOS = {};

/** The photo next to or above the fields of every step that shows one. */
const PHOTOS = {
  CarRentalDriver: PHOTO,
  CarRentalCar: STEP_PHOTO_1,
  CarRentalExtras: STEP_PHOTO_2
};

/** The steps of the wizard in the order of prolet__Plan__c: the page name, and its key in the Plan (its title). */
const STEPS = [
  { page: "CarRentalDriver", title: "CarRental_pag_driver" },
  { page: "CarRentalCar", title: "CarRental_pag_car" },
  { page: "CarRentalExtras", title: "CarRental_pag_extras" },
  { page: "CarRentalInvoice", title: "CarRental_pag_invoice" },
  { page: "CarRentalSummary", title: "CarRental_pag_summary" }
];

/**
 * The step shown last. Every page has a frame of its own, so a new step starts a new frame: the
 * step before is remembered here, for all of them (empty after the page was loaded: no animation then).
 */
let lastPage;

/**
 * The longest the turning ring of Next is shown (ms): when the server's answer to a move failed,
 * the wizard shows its error and nothing comes to the page. Only the ring: Next is never held.
 */
const RING_AT_MOST = 8000;

/** true when the wizard's messages of a page say something (a check that passed gives { name: null }) */
const saysSomething = (errors) =>
  Object.values(errors ?? {}).some((message) => message);

export default class CarRentalFrame extends LightningElement {
  /** The name of the page shown now (the page's "page" property). */
  @api page;
  /** The answers of all pages (the page's "model"). */
  @api model;
  /** The answers of the page shown now, as they are typed (the page's "data"). */
  @api data;
  /** The labels (the page's "l"). */
  @api l;
  /** For a page that has its own buttons (the summary with Submit). */
  @api hideButtons = false;
  /** The wizard's state (the page's "state"): a locked wizard shows the framework's own buttons. */
  @api state;

  /**
   * The messages of the page's fields (the page's "errors"). The wizard gives new ones each time it
   * checks the page, and every check that keeps the page (an empty required field, a validator …)
   * gives a message: then Next stops waiting at once. A check that passes gives none, and the
   * wizard goes on to the server.
   */
  @api
  get errors() {
    return this._errors;
  }
  set errors(value) {
    this._errors = value;
    if (this.busy && saysSomething(value)) {
      this.busy = false;
      clearTimeout(this.busyTimer);
    }
  }
  _errors;

  /**
   * true from a click on Next until the next step is shown or the page stays: Next shows that it
   * waits. A second click changes nothing: the wizard ignores a move while one is on its way.
   */
  busy = false;
  /** The step this frame has shown (one frame per page, but the frame of a page can stay). */
  shownPage;
  busyTimer;

  /** The photos of the steps are loaded at the start, so a step's photo is there at once. */
  connectedCallback() {
    for (const url of [
      ...Object.values(PHOTOS),
      ...Object.values(BACKGROUND_PHOTOS)
    ]) {
      const image = new Image();
      image.src = url;
    }
  }

  disconnectedCallback() {
    clearTimeout(this.busyTimer);
  }

  /**
   * A new step: it slides in softly, the page scrolls back to the top of it when it starts
   * above the screen, and the keyboard focus goes to it. Not on the first step shown.
   */
  renderedCallback() {
    if (this.page === this.shownPage) {
      return;
    }
    // the first step after the page was loaded comes without animation
    const first = lastPage === undefined || lastPage === this.page;
    this.shownPage = this.page;
    lastPage = this.page;
    this.busy = false;
    clearTimeout(this.busyTimer);
    const step = this.template.querySelector(".step-content");
    if (!step || first) {
      return;
    }
    step.classList.remove("step-enter");
    // reading the layout makes the animation start again
    step.getBoundingClientRect();
    step.classList.add("step-enter");
    const calm = window.matchMedia?.(
      "(prefers-reduced-motion: reduce)"
    ).matches;
    const top =
      this.template.querySelector(".frame")?.getBoundingClientRect().top ?? 0;
    // Salesforce's own header covers the top of the screen
    if (top < 110) {
      window.scrollBy({ top: top - 120, behavior: calm ? "auto" : "smooth" });
    }
    step.focus({ preventScroll: true });
  }

  get nextClass() {
    return `slds-button eh-button frame-button active${this.busy ? " busy" : ""}`;
  }

  get ariaBusy() {
    return this.busy ? "true" : "false";
  }

  get _l() {
    return this.l || {};
  }

  /** The answers of a page: the live ones of the page shown now, the saved ones of the others. */
  answers(page) {
    return (page === this.page ? this.data : this.model?.[page]) || {};
  }

  /** true when a step is part of the wizard with the answers given so far (the conditions of prolet__Plan__c). */
  isShown(page) {
    switch (page) {
      case "CarRentalExtras": // if (CarRentalCar.days > 7)
        return Number(this.answers("CarRentalCar").days) > 7;
      case "CarRentalInvoice": // if (CarRentalCar.carClass='luxury')
        return this.answers("CarRentalCar").carClass === "luxury";
      default:
        return true;
    }
  }

  /** The steps the user goes through: the ones whose condition is true, and always the current one. */
  get visibleSteps() {
    return STEPS.filter(
      (step) => step.page === this.page || this.isShown(step.page)
    );
  }

  get currentIndex() {
    return this.visibleSteps.findIndex((step) => step.page === this.page);
  }

  /** The text of a step: its label in the user's language, or its title. */
  text(step) {
    return step ? this._l[step.title] || step.title : "";
  }

  get hasPrev() {
    return this.currentIndex > 0;
  }

  get hasNext() {
    const index = this.currentIndex;
    return index !== -1 && index < this.visibleSteps.length - 1;
  }

  get showButtons() {
    // a locked (submitted) wizard: the framework shows its own Back and Next to look through
    // the pages, so the frame's would be a second pair (a frame from before had no state: shown)
    const locked = this.state !== undefined && isLockedState(this.state);
    return !this.hideButtons && !locked && (this.hasPrev || this.hasNext);
  }

  get backLabel() {
    return this._l.Wizard_act_back || "Back";
  }

  /** As in the framework: the Next button carries the title of the next step. */
  get nextLabel() {
    return (
      this.text(this.visibleSteps[this.currentIndex + 1]) ||
      this._l.Wizard_act_next ||
      "Next"
    );
  }

  /** The steps for the row on top. A step before the current one can be clicked to go back to it. */
  get steps() {
    const current = this.currentIndex;
    return this.visibleSteps.map((step, index) => ({
      page: step.page,
      number: index + 1,
      label: this.text(step),
      className: `step${index < current ? " passed" : ""}${index === current ? " active" : ""}`,
      // a step before the current one is a button; the current one is aria-current="step"
      passed: index < current,
      current: index === current ? "step" : null
    }));
  }

  handleStepClick(event) {
    const steps = this.visibleSteps;
    const index = steps.findIndex(
      (step) => step.page === event.currentTarget.dataset.page
    );
    if (index !== -1 && index < this.currentIndex) {
      this.navigate({ title: steps[index].title, page: steps[index].page });
    }
  }

  get currentTitle() {
    return this.text(this.visibleSteps[this.currentIndex]);
  }

  /** The look of the step shown: the wizard's, or the step's own. */
  get look() {
    return LOOKS[this.page] || WIZARD_LOOK;
  }

  get lookClass() {
    return `look look-${this.look.background}`;
  }

  /**
   * The page's width. With a photo next to the fields (on any step) the card is wider, on every
   * step: the card keeps its width from step to step.
   */
  get frameClass() {
    return "frame frame-medium with-side";
  }

  /** The background behind the page: a colour, a gradient, a photo, or none. */
  get backgroundStyle() {
    const { background, colors } = this.look;
    if (background === "color") {
      return `background-color: ${colors[0]}`;
    }
    if (background === "gradient") {
      return `background-image: linear-gradient(135deg, ${colors[0]}, ${colors[1]})`;
    }
    if (background === "photo" && BACKGROUND_PHOTOS[this.page]) {
      return `background-image: url("${BACKGROUND_PHOTOS[this.page]}")`;
    }
    return "";
  }

  get sheetClass() {
    return `sheet${this.look.card ? " card" : ""} sheet-${this.look.photo} photo-${this.look.photoSize}`;
  }

  get showBanner() {
    return this.look.photo === "banner" && Boolean(this.photoUrl);
  }

  get showSide() {
    return this.look.photo === "side" && Boolean(this.photoUrl);
  }

  /** The photo of the step shown: its own, or the wizard's. */
  get photoUrl() {
    return PHOTOS[this.page];
  }

  /** What the photo shows, for screen readers (empty: the photo is only decoration). */
  get photoText() {
    return "";
  }

  /**
   * Asks the wizard to change the page, with the event a page itself sends.
   * direction: "next" · "prev" · { title, page } to go back to a step.
   * The wizard checks the page (required fields, validators) before it goes forward.
   */
  navigate(direction) {
    this.dispatchEvent(
      new CustomEvent("pagechange", {
        bubbles: true,
        composed: true,
        detail: { direction, pageModel: { ...(this.data || {}) } }
      })
    );
  }

  handleBack() {
    this.navigate("prev");
  }

  handleNext() {
    // the wizard keeps a click from being two moves (a move on its way: the next is ignored), so
    // Next is never held here: after a failed answer of the server it works again at once
    this.busy = true;
    clearTimeout(this.busyTimer);
    // eslint-disable-next-line @lwc/lwc/no-async-operation
    this.busyTimer = setTimeout(() => {
      this.busy = false;
    }, RING_AT_MOST);
    this.navigate("next");
  }
}
