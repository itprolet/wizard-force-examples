import { LightningElement, api } from "lwc";
import TILE_1 from "@salesforce/resourceUrl/CarRentalTileCarPickupCitySofia";
import TILE_2 from "@salesforce/resourceUrl/CarRentalTileCarPickupCityPlovdiv";
import TILE_3 from "@salesforce/resourceUrl/CarRentalTileCarPickupCityVarna";
import TILE_4 from "@salesforce/resourceUrl/CarRentalTileCarCarClassEconomy";
import TILE_5 from "@salesforce/resourceUrl/CarRentalTileCarCarClassSuv";
import TILE_6 from "@salesforce/resourceUrl/CarRentalTileCarCarClassLuxury";

/**
 * The picture tiles of the carRental wizard: a dropdown shown as cards to click.
 *   <c-car-rental-tiles label=… name="…" items={…Options} value={data.…} required={…} error={…}
 *     page={page} onchange={changeHandler}></c-car-rental-tiles>
 * It sends "change" with { name, value }, as the framework's dropdown does.
 *
 * WIZARD-MAKER: generated by "npm run make style". It is written again when tiles or their photos
 * change, so changes made by hand here are replaced.
 */

/** The photos of the options: "Page.field.value" → its photo (an option without one shows only its text). */
const PHOTOS = {
  "CarRentalCar.pickupCity.sofia": TILE_1,
  "CarRentalCar.pickupCity.plovdiv": TILE_2,
  "CarRentalCar.pickupCity.varna": TILE_3,
  "CarRentalCar.carClass.economy": TILE_4,
  "CarRentalCar.carClass.suv": TILE_5,
  "CarRentalCar.carClass.luxury": TILE_6
};

export default class CarRentalTiles extends LightningElement {
  @api label;
  @api name;
  /** The options: [{ label, value }] */
  @api items = [];
  @api value;
  @api required;
  @api error;
  /** The page the tiles are on: their photos are found with it. */
  @api page;

  get tiles() {
    const photoOf = (item) => PHOTOS[`${this.page}.${this.name}.${item.value}`];
    // when some options have a photo, the others get a placeholder: every tile is as high
    const somePhotos = (this.items || []).some(photoOf);
    const hasValue = (this.items || []).some(
      (item) => String(item.value) === String(this.value ?? "")
    );
    return (this.items || []).map((item, index) => {
      const value = String(item.value);
      const selected = value === String(this.value ?? "");
      const photo = photoOf(item);
      return {
        value,
        label: item.label,
        photo,
        placeholder: somePhotos && !photo,
        initial: String(item.label ?? value)
          .trim()
          .charAt(0)
          .toUpperCase(),
        checked: selected ? "true" : "false",
        // Tab stops on one tile: the chosen one, or the first (the arrow keys move from there)
        tabindex: selected || (!hasValue && index === 0) ? "0" : "-1",
        className: `tile${selected ? " selected" : ""}${photo ? " with-photo" : ""}`
      };
    });
  }

  handleClick(event) {
    this.choose(event.currentTarget.dataset.value);
  }

  choose(value) {
    this.dispatchEvent(
      new CustomEvent("change", { detail: { name: this.name, value } })
    );
  }

  /** The arrow keys move to the next or the previous tile and choose it, as in a radio group. */
  handleKeydown(event) {
    const step = {
      ArrowRight: 1,
      ArrowDown: 1,
      ArrowLeft: -1,
      ArrowUp: -1
    }[event.key];
    const tiles = [...this.template.querySelectorAll(".tile")];
    const at = tiles.indexOf(event.target);
    if (
      at === -1 ||
      (step === undefined && event.key !== "Home" && event.key !== "End")
    ) {
      return;
    }
    event.preventDefault();
    let next = at + (step ?? 0);
    if (event.key === "Home") {
      next = 0;
    } else if (event.key === "End") {
      next = tiles.length - 1;
    }
    next = (next + tiles.length) % tiles.length;
    tiles[next].focus();
    this.choose(tiles[next].dataset.value);
  }
}
